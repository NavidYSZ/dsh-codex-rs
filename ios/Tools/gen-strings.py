def camel(key):
    parts = re.split(r'[._]', key)
    out = parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    return out


def args_of(fmt):
    """The Swift parameter types a format string takes, in order."""
    out = []
    for m in re.finditer(r'%(lld|@|d)', fmt):
        out.append('Int' if m.group(1) in ('lld', 'd') else 'String')
    return out


def swift_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    catalog = {'sourceLanguage': 'de', 'version': '1.0', 'strings': {}}
    lines = [
        '// Generated by Tools/gen-strings.py — do not edit by hand. German is the source language, English the',
        '// translation; both live in Resources/Localizable.xcstrings. Edit the table in the script and run it again.',
        'import Foundation',
        '',
        '/// Every string the app shows, as typed accessors (so a key the code uses always exists in the catalog).',
        'enum L {',
    ]
    for entry in S:
        key = entry[0]
        name = camel(key)
        if isinstance(entry[1], dict):
            de_one, en_one = entry[1]['one']
            de_other, en_other = entry[1]['other']
            catalog['strings'][key] = {
                'extractionState': 'manual',
                'localizations': {
                    'de': {'variations': {'plural': {'one': {'stringUnit': {'state': 'translated', 'value': de_one}},
                                                     'other': {'stringUnit': {'state': 'translated', 'value': de_other}}}}},
                    'en': {'variations': {'plural': {'one': {'stringUnit': {'state': 'translated', 'value': en_one}},
                                                     'other': {'stringUnit': {'state': 'translated', 'value': en_other}}}}},
                },
            }
            types = args_of(de_other)
            params = ', '.join(f'_ a{i}: {t}' for i, t in enumerate(types))
            call = ', '.join(f'a{i}' for i in range(len(types)))
            lines.append(f'    static func {name}({params}) -> String {{')
            lines.append(f'        String.localizedStringWithFormat(String(localized: {swift_string(key)}, defaultValue: {swift_string(de_other)}), {call})')
            lines.append('    }')
            continue
        _, de, en = entry
        catalog['strings'][key] = {
            'extractionState': 'manual',
            'localizations': {
                'de': {'stringUnit': {'state': 'translated', 'value': de}},
                'en': {'stringUnit': {'state': 'translated', 'value': en}},
            },
        }
        types = args_of(de)
        if types:
            params = ', '.join(f'_ a{i}: {t}' for i, t in enumerate(types))
            call = ', '.join(f'a{i}' for i in range(len(types)))
            lines.append(f'    static func {name}({params}) -> String {{')
            lines.append(f'        String.localizedStringWithFormat(String(localized: {swift_string(key)}, defaultValue: {swift_string(de)}), {call})')
            lines.append('    }')
        else:
            lines.append(f'    static var {name}: String {{ String(localized: {swift_string(key)}, defaultValue: {swift_string(de)}) }}')
    lines.append('')
    lines.append('    /// A key by name, for tables such as the work-group labels (`work.live.<activity>`); nil when unknown.')
    lines.append('    static func lookup(_ key: String) -> String? {')
    lines.append('        guard known.contains(key) else { return nil }')
    lines.append('        return String(localized: String.LocalizationValue(key))')
    lines.append('    }')
    lines.append('')
    keys = ', '.join(swift_string(e[0]) for e in S)
    lines.append(f'    static let known: Set<String> = [{keys}]')
    lines.append('}')
    lines.append('')
    os.makedirs(os.path.join(ROOT, 'Aether/Core/L10n'), exist_ok=True)
